const readmeImageLimit = 20 << 20

type subject struct {
	tool    pub_models.PartsCaller
	store   *assettest.Memory
	gen     *imagegentest.Fake
	cfgs    *[]imagegen.GeneratorConfig
	newGens func() int
}

var testConfig = imagegen.GeneratorConfig{Model: "gpt-image-1-mini", ConfigDir: "/clai-config"}

func newSubject(gen *imagegentest.Fake, refusal error) subject {
	store := assettest.NewMemory()
	var mu sync.Mutex
	var cfgs []imagegen.GeneratorConfig
	newGen := func(cfg imagegen.GeneratorConfig) (imagegen.ImageGenerator, error) {
		mu.Lock()
		defer mu.Unlock()
		cfgs = append(cfgs, cfg)
		if refusal != nil {
			return nil, refusal
		}
		return gen, nil
	}
	return subject{
		tool:  tool.NewGenerateImageTool(testConfig, newGen, store),
		store: store,
		gen:   gen,
		cfgs:  &cfgs,
		newGens: func() int {
			mu.Lock()
			defer mu.Unlock()
			return len(cfgs)
		},
	}
}

func pngOf(t *testing.T, w int) []byte {
	t.Helper()
	var buf bytes.Buffer
	if err := png.Encode(&buf, image.NewGray(image.Rect(0, 0, w, 1))); err != nil {
		t.Fatalf("encode png: %v", err)
	}
	return buf.Bytes()
}

func jpegOf(t *testing.T) []byte {
	t.Helper()
	var buf bytes.Buffer
	if err := jpeg.Encode(&buf, image.NewGray(image.Rect(0, 0, 2, 2)), nil); err != nil {
		t.Fatalf("encode jpeg: %v", err)
	}
	return buf.Bytes()
}

func refOf(data []byte, ext string) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:]) + "." + ext
}

func generated(data []byte, mime, revised string) imagegen.GeneratedImage {
	return imagegen.GeneratedImage{Image: asset.Image{Data: data, MIME: mime}, RevisedPrompt: revised}
}

func wantImage(ref, mime, revised string) []pub_models.Part {
	text := "generated image " + ref[:6] + " saved at " + path.Join(assettest.MemoryDir, ref)
	if revised != "" {
		text += "\nrevised prompt: " + revised
	}
	return []pub_models.Part{
		pub_models.TextPart{Text: text},
		pub_models.ImagePart{Asset: ref, MIME: mime, Origin: pub_models.OriginGenerated},
	}
}

func assertNotCalled(t *testing.T, s subject) {
	t.Helper()
	if n := s.newGens(); n != 0 {
		t.Fatalf("newGen called %d times, want 0", n)
	}
	if s.gen != nil && len(s.gen.Requests()) != 0 {
		t.Fatalf("Generate called with %+v, want no call", s.gen.Requests())
	}
}

// CallParts.1, CallParts.8, I6, I7, AC1
func TestGenerateImage_Generates(t *testing.T) {
	first, second := pngOf(t, 3), jpegOf(t)
	s := newSubject(&imagegentest.Fake{Images: []imagegen.GeneratedImage{
		generated(first, "image/png", ""), generated(second, "image/jpeg", ""),
	}}, nil)
	if n := s.newGens(); n != 0 {
		t.Fatalf("newGen called %d times at construction, want 0", n)
	}

	parts, err := s.tool.CallParts(t.Context(), pub_models.Input{"prompt": "a fox in the snow", "size": "auto"})
	if err != nil {
		t.Fatalf("CallParts: %v", err)
	}
	firstRef, secondRef := refOf(first, "png"), refOf(second, "jpg")
	want := append(wantImage(firstRef, "image/png", ""), wantImage(secondRef, "image/jpeg", "")...)
	if !reflect.DeepEqual(parts, want) {
		t.Fatalf("parts = %#v, want %#v", parts, want)
	}
	for _, p := range parts {
		if img, ok := p.(pub_models.ImagePart); ok && (img.Origin != pub_models.OriginGenerated || img.Data != nil) {
			t.Fatalf("image %+v, want a stored part with Origin generated", img)
		}
	}
	if names := s.store.Names(); !reflect.DeepEqual(names, slices.Sorted(slices.Values([]string{firstRef, secondRef}))) {
		t.Fatalf("store holds %v, want both generated images", names)
	}
	stored, err := s.store.Load(firstRef)
	if err != nil || !bytes.Equal(stored.Data, first) {
		t.Fatalf("Load(%s) = %v, %v; want the generated bytes", firstRef, stored, err)
	}
	wantReq := []imagegen.ImageRequest{{Prompt: "a fox in the snow", Size: "auto"}}
	if got := s.gen.Requests(); !reflect.DeepEqual(got, wantReq) {
		t.Fatalf("requests = %+v, want %+v", got, wantReq)
	}

	if _, err := s.tool.CallParts(t.Context(), pub_models.Input{"prompt": "again"}); err != nil {
		t.Fatalf("second CallParts: %v", err)
	}
	if n := s.newGens(); n != 1 {
		t.Fatalf("newGen called %d times across two calls, want 1", n)
	}
	if cfgs := *s.cfgs; !reflect.DeepEqual(cfgs, []imagegen.GeneratorConfig{testConfig}) {
		t.Fatalf("newGen got %+v, want %+v", cfgs, testConfig)
	}
}

