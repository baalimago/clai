// CallParts.2
func TestGenerateImage_EditByPath(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	input, output := pngOf(t, 7), pngOf(t, 8)
	s := newSubject(&imagegentest.Fake{Images: []imagegen.GeneratedImage{generated(output, "image/png", "")}}, nil)
	writeFile(t, filepath.Join(home, "img.png"), input)

	if _, err := s.tool.CallParts(t.Context(), pub_models.Input{"prompt": "watercolour", "input_images": []string{"~/img.png"}}); err != nil {
		t.Fatalf("CallParts: %v", err)
	}
	if got := s.gen.Requests(); len(got) != 1 || !reflect.DeepEqual(got[0].Inputs, []asset.Image{{Data: input, MIME: "image/png"}}) {
		t.Fatalf("requests = %+v, want the PNG at ~/img.png as Inputs[0]", got)
	}
	if names := s.store.Names(); !reflect.DeepEqual(names, []string{refOf(output, "png")}) {
		t.Fatalf("store holds %v, want only the generated image", names)
	}

	notImage := writeFile(t, filepath.Join(home, "notes.txt"), []byte("plain text, not pixels\n"))
	huge := writeFile(t, filepath.Join(home, "huge.png"), input)
	if err := os.Truncate(huge, readmeImageLimit+1); err != nil {
		t.Fatalf("truncate: %v", err)
	}
	// Write-only: a read before the size check fails with a permission error instead.
	if err := os.Chmod(huge, 0o200); err != nil {
		t.Fatalf("chmod: %v", err)
	}
	missing := filepath.Join(home, "absent.png")
	cases := []struct {
		entry, path string
		check       func(error) bool
	}{
		{"~/notes.txt", notImage, func(err error) bool { return errors.Is(err, asset.ErrNotImage) }},
		{huge, huge, func(err error) bool {
			var tooLarge *asset.ImageTooLargeError
			return errors.As(err, &tooLarge) &&
				*tooLarge == asset.ImageTooLargeError{Path: huge, Size: readmeImageLimit + 1, Limit: readmeImageLimit}
		}},
		{missing, missing, func(err error) bool { return errors.Is(err, fs.ErrNotExist) }},
		{home, home, func(err error) bool { return errors.Is(err, fs.ErrInvalid) }},
	}
	for _, c := range cases {
		_, err := s.tool.CallParts(t.Context(), pub_models.Input{"prompt": "p", "input_images": []any{c.entry}})
		if !c.check(err) || !strings.Contains(err.Error(), c.path) {
			t.Fatalf("input %q: err = %v, want the typed error naming %s", c.entry, err, c.path)
		}
	}
	if n := len(s.gen.Requests()); n != 1 {
		t.Fatalf("Generate called %d times, want only the first, valid call", n)
	}
	if names := s.store.Names(); len(names) != 1 {
		t.Fatalf("store holds %v, want only the generated image", names)
	}
}

func writeFile(t *testing.T, path string, data []byte) string {
	t.Helper()
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatalf("write %s: %v", path, err)
	}
	return path
}

