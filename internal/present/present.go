// Package present shows a generated image to the user, as a line or as tool-block rows,
// and optionally opens it.
package present

import (
	"errors"
	"fmt"
	"io"
	"net/url"
	"os/exec"
	"runtime"
	"strings"
	"time"

	"github.com/baalimago/clai/internal/asset"
	"github.com/baalimago/clai/internal/utils"
)

// Opener launches the user's image viewer on a file. It is a parameter type of
// Options, as io.Writer is.
type Opener interface {
	// Open launches the viewer on path.
	//  1. It returns nil once the launcher command exits with status 0.
	Open(path string) error
}

type Shown struct {
	Handle  string
	Path    string // absolute
	Rebus   string // emoji that summarise the image; "" for none
	Details Details
}

// Details describe how an image was made; a zero field is left out of the line.
type Details struct {
	Model   string
	Size    asset.Size
	Bytes   int
	Elapsed time.Duration
}

// DetailsOf describes data, generated by model in elapsed.
//  1. Size comes from asset.Measure, and is zero when the format has none; Bytes is
//     len(data).
func DetailsOf(data []byte, model string, elapsed time.Duration) Details {
	size, _ := asset.Measure(data)
	return Details{Model: model, Size: size, Bytes: len(data), Elapsed: elapsed}
}

type Options struct {
	Out      io.Writer
	Terminal bool // Out is a terminal
	Color    bool // false when NO_COLOR is set or raw mode is on
	AutoOpen bool // the auto-open-images config value or the -open flag
	Opener   Opener
}

type Presenter interface {
	// Present writes one line for img and opens it when allowed.
	//  1. With Terminal && Color, it writes "▸ image <handle> → <url>\n", where <url> is
	//     file://<Path> with the path percent-encoded, so terminals can open it on click.
	//     The marker ▸ has the theme's primary colour, as on the progress board. The URL
	//     is coloured with the theme's tool colour and wrapped in an OSC 8 hyperlink to
	//     itself. A non-empty Rebus follows the marker as "[<rebus>] ". Details follow
	//     the handle as " · <model> · <W>×<H> (<ratio>) · <size> · <time>", in the
	//     theme's secondary colour, each part left out when zero.
	//  2. Otherwise it writes exactly Path + "\n", with no escape codes, so
	//     `| xargs xdg-open` works.
	//  3. Opener.Open(Path) is called exactly once when AutoOpen && Terminal, and never
	//     otherwise (U2).
	//  4. When Open fails, Present returns *OpenFailedError{Path, Cause} after the line is
	//     written. The line is already on Out when Present returns, so a later failure
	//     cannot take it back (I7). Callers treat the error as a non-fatal notice (U2).
	//  5. When the write fails, Present returns the write error and does not call Open.
	Present(img Shown) error
	// Open opens img as Present does, without writing anything.
	//  1. Opener.Open(Path) is called exactly once when AutoOpen && Terminal, and never
	//     otherwise.
	//  2. When Open fails, it returns *OpenFailedError{Path, Cause}.
	Open(img Shown) error
	// Rows is img's line as two rows for a tool block, the URL on a row of its own.
	//  1. They are "▸ [<rebus>] image <handle> · <details>" and "→ <file URL>", coloured
	//     and linked as Present.1 colours and links them when Color is set.
	//  2. Without Color they are plain text.
	Rows(img Shown) []string
}

func New(opts Options) Presenter {
	return presenter{opts: opts}
}

// NewCommandOpener runs command with the path as its single argument and waits for it
// to exit.
//  1. command "" means the platform default: "xdg-open" on Linux, "open" on macOS. On
//     any other platform it is *OpenerUnavailableError{Command:""}, raised by Open.
//  2. A command not on PATH makes Open fail with *OpenerUnavailableError{Command}.
//  3. A non-zero exit makes Open fail with *OpenFailedError, carrying the exit status.
//  4. The argv is exactly [command, path]. No shell is involved.
func NewCommandOpener(command string) Opener {
	return newCommandOpener(command, runtime.GOOS)
}

type OpenFailedError struct {
	Path  string
	Cause error
}

func (e *OpenFailedError) Error() string {
	return fmt.Sprintf("open image %s: %v", e.Path, e.Cause)
}

func (e *OpenFailedError) Unwrap() error { return e.Cause }

type OpenerUnavailableError struct{ Command string }

func (e *OpenerUnavailableError) Error() string {
	if e.Command == "" {
		return "no default image opener on this platform: set image-opener in the config"
	}
	return fmt.Sprintf("image opener %q is not an executable on PATH", e.Command)
}

const (
	marker    = "▸"
	arrow     = "→"
	ansiReset = "\x1b[0m"
)

var (
	errNoOutput = errors.New("present: no output writer")
	errNoOpener = errors.New("no image opener configured")
)

type presenter struct{ opts Options }

func (p presenter) Present(img Shown) error {
	if p.opts.Out == nil {
		return errNoOutput
	}
	if _, err := io.WriteString(p.opts.Out, p.line(img)); err != nil {
		return fmt.Errorf("write image line: %w", err)
	}
	return p.Open(img)
}

func (p presenter) Open(img Shown) error {
	if !p.opts.AutoOpen || !p.opts.Terminal {
		return nil
	}
	return p.open(img.Path)
}

func (p presenter) line(img Shown) string {
	if !p.opts.Terminal || !p.opts.Color {
		return img.Path + "\n"
	}
	return strings.Join(p.Rows(img), " ") + "\n"
}

func (p presenter) Rows(img Shown) []string {
	url := fileURL(img.Path)
	mark, details, link := marker, img.Details.text(), url
	if p.opts.Color {
		mark = colorize(utils.TableTheme().Primary, marker)
		details = colorize(utils.TableTheme().Secondary, details)
		link = hyperlink(url, colorize(utils.RoleColor("tool"), url))
	}
	return []string{mark + " " + rebusText(img.Rebus) + "image " + img.Handle + details, arrow + " " + link}
}

func colorize(color, s string) string {
	if color == "" || s == "" {
		return s
	}
	return color + s + ansiReset
}

func (p presenter) open(path string) error {
	if p.opts.Opener == nil {
		return &OpenFailedError{Path: path, Cause: errNoOpener}
	}
	err := p.opts.Opener.Open(path)
	if err == nil {
		return nil
	}
	var failed *OpenFailedError
	if errors.As(err, &failed) && failed.Path == path {
		return failed
	}
	return &OpenFailedError{Path: path, Cause: err}
}

// hyperlink wraps text in an OSC 8 terminal hyperlink to target.
func hyperlink(target, text string) string {
	return "\x1b]8;;" + target + "\x1b\\" + text + "\x1b]8;;\x1b\\"
}

type commandOpener struct{ command string }

func newCommandOpener(command, goos string) Opener {
	if command == "" {
		command = defaultLauncher(goos)
	}
	return commandOpener{command: command}
}

func defaultLauncher(goos string) string {
	switch goos {
	case "linux":
		return "xdg-open"
	case "darwin":
		return "open"
	default:
		return ""
	}
}

func (o commandOpener) Open(path string) error {
	if o.command == "" {
		return &OpenerUnavailableError{}
	}
	if _, err := exec.LookPath(o.command); err != nil {
		return &OpenerUnavailableError{Command: o.command}
	}
	if err := exec.Command(o.command, path).Run(); err != nil {
		return &OpenFailedError{Path: path, Cause: err}
	}
	return nil
}

// text is the details segment of the line, or "" when every field is zero.
func (d Details) text() string {
	var parts []string
	if d.Model != "" {
		parts = append(parts, d.Model)
	}
	if d.Size.Width > 0 && d.Size.Height > 0 {
		parts = append(parts, fmt.Sprintf("%d×%d (%s)", d.Size.Width, d.Size.Height, ratio(d.Size)))
	}
	if d.Bytes > 0 {
		parts = append(parts, byteSize(d.Bytes))
	}
	if d.Elapsed > 0 {
		parts = append(parts, elapsed(d.Elapsed))
	}
	if len(parts) == 0 {
		return ""
	}
	return " · " + strings.Join(parts, " · ")
}

// maxRatioTerm is the largest term a ratio keeps in whole numbers.
const maxRatioTerm = 32

func ratio(s asset.Size) string {
	a, b := s.Width, s.Height
	for b != 0 {
		a, b = b, a%b
	}
	w, h := s.Width/a, s.Height/a
	if w <= maxRatioTerm && h <= maxRatioTerm {
		return fmt.Sprintf("%d:%d", w, h)
	}
	return fmt.Sprintf("%.2f:1", float64(s.Width)/float64(s.Height))
}

// byteSize uses SI units; a size that would round to 1000 KB is shown in MB.
func byteSize(n int) string {
	switch {
	case n < 1000:
		return fmt.Sprintf("%d B", n)
	case n < 999_500:
		return fmt.Sprintf("%.0f KB", float64(n)/1000)
	default:
		return fmt.Sprintf("%.1f MB", float64(n)/1_000_000)
	}
}

func elapsed(d time.Duration) string {
	switch {
	case d < time.Millisecond:
		return "<1ms"
	case d < time.Second:
		return d.Round(time.Millisecond).String()
	default:
		return d.Round(time.Second).String()
	}
}

func fileURL(path string) string { return (&url.URL{Scheme: "file", Path: path}).String() }

func rebusText(rebus string) string {
	if rebus == "" {
		return ""
	}
	return "[" + rebus + "] "
}
